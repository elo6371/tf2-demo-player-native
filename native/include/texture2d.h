#pragma once

#include <Windows.h>
#include <d3d11.h>
#include <cstdint>
#include <string>
#include <vector>
#include <wrl/client.h>

namespace tf2::native {

class Texture2D {
public:
  // `maxBytes` is the guard against a runaway allocation. It defaults to the
  // 64 MiB the ordinary textures have always been held to; the world atlas
  // passes its own budget, because a 64-tile atlas of 512-texel tiles is
  // 67.6 MiB by construction and refusing it silently downgraded the whole
  // world to a single material texture.
  // A second entry point, not a defaulted argument on the first, because the
  // mip chain has to be GENERATED by the device context and a caller that
  // passes a null context would silently get a one-level texture -- exactly the
  // state the world atlas was in when every distance view aliased.
  bool create(ID3D11Device* device, const std::vector<std::uint8_t>& rgba,
    UINT width, UINT height, std::string* error = nullptr,
    std::uint64_t maxBytes = 64ull * 1024ull * 1024ull);
  bool createMipped(ID3D11Device* device, ID3D11DeviceContext* context,
    const std::vector<std::uint8_t>& rgba, UINT width, UINT height,
    std::string* error = nullptr,
    std::uint64_t maxBytes = 64ull * 1024ull * 1024ull);
  void reset();
  ID3D11ShaderResourceView* view() const { return view_.Get(); }
  UINT width() const { return width_; }
  UINT height() const { return height_; }
  // Owner 2026-11-26 19:45: why the texture was refused, for the one caller that
  // has a fallback (the world atlas retries at the baseline extent). FAILED() from
  // CreateTexture2D is exactly E_OUTOFMEMORY when the device ran out; every earlier
  // refusal -- bad arguments, a buffer that does not match the dimensions, the
  // caller's byte budget -- leaves E_FAIL. S_OK before any call and after success.
  HRESULT failureHresult() const { return failureHresult_; }

private:
  HRESULT failureHresult_ = S_OK;
  Microsoft::WRL::ComPtr<ID3D11Texture2D> texture_;
  Microsoft::WRL::ComPtr<ID3D11ShaderResourceView> view_;
  UINT width_ = 0;
  UINT height_ = 0;
};

} // namespace tf2::native
